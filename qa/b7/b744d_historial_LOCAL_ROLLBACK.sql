-- Replica de la tabla histórica inventariada.
CREATE TABLE public.pedido_estados_historial (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id bigint NOT NULL
  REFERENCES public.pedidos(id) ON DELETE CASCADE,
 mesa_id bigint,
 estado_anterior text,
 estado_nuevo text NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT now()
);

-- Función real recuperada de producción.
CREATE FUNCTION public.log_pedido_estado()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
 IF TG_OP = 'INSERT' THEN
  INSERT INTO public.pedido_estados_historial
   (pedido_id,mesa_id,estado_anterior,estado_nuevo,changed_at)
  VALUES
   (NEW.id,NEW.mesa_id,NULL,NEW.estado,
    coalesce(NEW.creado_en,now()));
  RETURN NEW;
 END IF;

 IF TG_OP = 'UPDATE'
    AND OLD.estado IS DISTINCT FROM NEW.estado THEN
  INSERT INTO public.pedido_estados_historial
   (pedido_id,mesa_id,estado_anterior,estado_nuevo,changed_at)
  VALUES
   (NEW.id,NEW.mesa_id,OLD.estado,NEW.estado,now());
 END IF;
 RETURN NEW;
END;
$function$;

CREATE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
 NEW.updated_at = now();
 RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_log_pedido_estado
AFTER INSERT OR UPDATE ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION public.log_pedido_estado();

CREATE TRIGGER trg_pedidos_updated_at
BEFORE UPDATE ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trg_items_pedido_updated_at
BEFORE UPDATE ON public.items_pedido
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

